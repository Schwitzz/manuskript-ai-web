// Generates src/lib/api-types.ts from the server's OpenAPI schema.
//   cd server && uv run python -c "import json; from app.main import create_app; \
//     print(json.dumps(create_app().openapi()))" > ../web/openapi.json
//   cd web && node scripts/gen-types.mjs
// Only the subset of OpenAPI that FastAPI/pydantic emits for this project is handled.
import { readFileSync, writeFileSync } from 'node:fs';

const spec = JSON.parse(readFileSync(new URL('../openapi.json', import.meta.url), 'utf8'));
const schemas = spec.components?.schemas ?? {};

function ts(s, indent = '') {
	if (!s) return 'unknown';
	if (s.$ref) return s.$ref.split('/').pop();
	if (s.anyOf || s.oneOf) return (s.anyOf ?? s.oneOf).map((x) => ts(x, indent)).join(' | ');
	if (s.enum) return s.enum.map((v) => JSON.stringify(v)).join(' | ');
	if (s.const !== undefined) return JSON.stringify(s.const);
	switch (s.type) {
		case 'string':
			return 'string';
		case 'integer':
		case 'number':
			return 'number';
		case 'boolean':
			return 'boolean';
		case 'null':
			return 'null';
		case 'array':
			if (s.prefixItems) return `[${s.prefixItems.map((x) => ts(x, indent)).join(', ')}]`;
			return `${wrap(ts(s.items, indent))}[]`;
		case 'object': {
			if (s.properties) return objectType(s, indent);
			if (s.additionalProperties && s.additionalProperties !== true)
				return `Record<string, ${ts(s.additionalProperties, indent)}>`;
			return 'Record<string, unknown>';
		}
		default:
			return 'unknown';
	}
}

const wrap = (t) => (/[|&]/.test(t) ? `(${t})` : t);

function objectType(s, indent) {
	const required = new Set(s.required ?? []);
	const inner = indent + '\t';
	const lines = Object.entries(s.properties).map(([k, v]) => {
		const key = /^[A-Za-z_$][\w$]*$/.test(k) ? k : JSON.stringify(k);
		// Properties with a default are always present in responses and optional in requests.
		const optional = required.has(k) ? '' : '?';
		return `${inner}${key}${optional}: ${ts(v, inner)};`;
	});
	return `{\n${lines.join('\n')}\n${indent}}`;
}

let out =
	'// GENERATED by scripts/gen-types.mjs from the server OpenAPI schema. Do not edit by hand.\n\n';
for (const [name, schema] of Object.entries(schemas)) {
	out +=
		schema.type === 'object' && schema.properties
			? `export interface ${name} ${objectType(schema, '')}\n\n`
			: `export type ${name} = ${ts(schema)};\n\n`;
}

// Operations: one entry per route, so calls can be checked against the server.
out += 'export interface Routes {\n';
for (const [path, methods] of Object.entries(spec.paths)) {
	for (const [method, op] of Object.entries(methods)) {
		const body = op.requestBody?.content?.['application/json']?.schema;
		const ok = op.responses?.['200'] ?? op.responses?.['201'];
		const res = ok?.content?.['application/json']?.schema;
		out += `\t${JSON.stringify(`${method.toUpperCase()} ${path}`)}: { body: ${body ? ts(body, '\t') : 'never'}; response: ${res && Object.keys(res).length ? ts(res, '\t') : 'unknown'} };\n`;
	}
}
out += '}\n';

writeFileSync(new URL('../src/lib/api-types.ts', import.meta.url), out);
console.log(`wrote src/lib/api-types.ts (${Object.keys(schemas).length} schemas, ${Object.keys(spec.paths).length} paths)`);
